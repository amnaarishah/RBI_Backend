def seed():
    db = SessionLocal()
    try:
        existing = db.query(Equipment).count()
        if existing > 0:
            print(f"Database already has {existing} equipment records. Skipping seed.")
            return
        for item in DEMO_EQUIPMENT:
            db.add(Equipment(**item))
        db.commit()
        print(f"✅ Seeded {len(DEMO_EQUIPMENT)} demo equipment records.")
    except Exception as e:
        db.rollback()
        print(f"❌ Seed error: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed()
